// LocalStorage helpers for reading progress
const STORAGE_KEY = 'hanyu_stories_progress_v1';

export interface StoryProgress {
  currentPage: number;
  completed: boolean;
  completedAt?: string;
  earnedXp?: number;
}

export function getStoryProgress(storyId: string): StoryProgress {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return { currentPage: 1, completed: false };
    const data = JSON.parse(raw);
    return data[storyId] || { currentPage: 1, completed: false };
  } catch {
    return { currentPage: 1, completed: false };
  }
}

export function saveStoryProgress(storyId: string, page: number, isCompleted = false, xpAwarded = 0): void {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    const data = raw ? JSON.parse(raw) : {};
    const existing = data[storyId] || { currentPage: 1, completed: false };

    data[storyId] = {
      currentPage: Math.max(existing.currentPage || 1, page),
      completed: existing.completed || isCompleted,
      completedAt: isCompleted ? new Date().toISOString() : existing.completedAt,
      earnedXp: (existing.earnedXp || 0) + xpAwarded,
    };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
  } catch (err) {
    console.error('Failed to save story progress', err);
  }
}

export function getAllStories(): Story[] {
  return STORIES;
}

export function getStoryById(id: string): Story | undefined {
  return STORIES.find((s) => s.id === id);
}

// Fallback auto-aligner if tokens are not explicitly defined in a new story
export function getPageTokens(page: StoryPage): CharToken[] {
  if (page.tokens && page.tokens.length > 0) {
    return page.tokens;
  }
  // Simple fallback character by character
  const chars = Array.from(page.zh);
  const words = page.py.replace(/[,\.!\?"':;]/g, '').trim().split(/\s+/);
  let pIdx = 0;
  return chars.map((c) => {
    if (/[，。！？、“”：；（）…—\s]/.test(c)) {
      return { c };
    }
    const p = words[pIdx] || '';
    pIdx++;
    return { c, p };
  });
}

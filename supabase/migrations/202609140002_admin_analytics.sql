-- Secure one-time provisioning. This intentionally aborts if the intended account
-- does not exist yet, preventing a later registrant from claiming admin privileges.
do $$
declare
  intended_admin_id uuid;
begin
  select p.id into intended_admin_id
  from public.profiles p
  where p.username = 'mogiadev';

  if intended_admin_id is null then
    raise exception 'Register the intended admin account before applying this migration';
  end if;

  if exists (
    select 1 from public.admin_users a where a.user_id <> intended_admin_id
  ) then
    raise exception 'A different administrator is already provisioned';
  end if;

  insert into public.admin_users (user_id)
  values (intended_admin_id)
  on conflict (user_id) do nothing;
end;
$$;
